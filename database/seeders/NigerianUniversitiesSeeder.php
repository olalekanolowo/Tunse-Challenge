    /**
     * Federal, state and private Nigerian universities students can register under.
     *
     * Only inserts institutions that don't exist yet (matched by short code or name),
     * so it is safe to re-run in production without undoing admin edits such as
     * renames or deactivations. State names match StatesLgaSeeder ("FCT" for Abuja).
     */
    public function run(): void
    {
        foreach ($this->universities() as [$name, $shortCode, $state]) {
            $exists = Institution::where('short_code', $shortCode)->orWhere('name', $name)->exists();

            if ($exists) {
                continue;
            }

            Institution::create([
                'name' => $name,
                'short_code' => $shortCode,
                'state' => $state,
                'active' => true,
            ]);
        }
    }

